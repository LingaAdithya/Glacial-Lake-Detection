# `predict_tta` is needed for the inference loop.
def predict_tta(model, images):
    # Original
    pred1 = torch.sigmoid(
        model(images)
    )
    # Horizontal Flip
    hflip = torch.flip(
        images,
        dims=[3]
    )
    pred2 = torch.sigmoid(
        model(hflip)
    )
    pred2 = torch.flip(
        pred2,
        dims=[3]
    )
    # Vertical Flip
    vflip = torch.flip(
        images,
        dims=[2]
    )
    pred3 = torch.sigmoid(
        model(vflip)
    )
    pred3 = torch.flip(
        pred3,
        dims=[2]
    )
    final_pred = (
        pred1 +
        pred2 +
        pred3
    ) / 3.0
    return final_pred

