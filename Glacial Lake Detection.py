def consistency_loss(
    student_pred,
    teacher_pred
):

    student_prob = torch.sigmoid(
        student_pred
    )

    teacher_prob = torch.sigmoid(
        teacher_pred
    )

    return mse(
        student_prob,
        teacher_prob
    )

